package org.apache.calcite.adapter.jira;

import org.apache.calcite.linq4j.Enumerable;

/** A Jira table that {@link JiraTableModify} writes. */
public interface JiraWritable {

  /**
   * Executes an INSERT, UPDATE or DELETE. Called from code generated by {@link JiraTableModify}.
   *
   * @param operation     INSERT, UPDATE or DELETE
   * @param rows          for INSERT, one value per table column; for DELETE, the table row; for
   *                      UPDATE, the table row followed by one new value per update column
   * @param updateColumns comma-separated update column names (UPDATE only)
   * @return single-element enumerable holding the number of rows written
   */
  Enumerable<Long> modify(String operation, Enumerable<Object[]> rows, String updateColumns);
}
